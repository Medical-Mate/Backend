package com.jinryomate.backend.appointment.entity;

/**
 * 일정이 어디서 만들어졌는지.
 *
 * <p>시안 {@code 1r-2-A} 가 <b>"진료 후 기록에서 자동으로 만들었어요"</b> 를 찍는다.
 * 환자가 손으로 만든 일정과 구별이 안 되면 그 문구를 못 그린다.
 *
 * <p>"모름" 자리를 두지 않는다 — 재방문에서 온 게 아니면 사람이 만든 것이다.
 */
public enum Origin {

    /** 환자가 캘린더에서 직접 만들었다. 화면 {@code 1r-4}. */
    MANUAL,

    /**
     * 진료 후 기록의 재방문에서 나왔다.
     *
     * <p>서버가 자동으로 만들지는 않는다. 환자가 {@code 1q-1} 에서 보고 등록하는
     * 흐름이라 앱이 만들고, 우리는 그게 어디서 왔는지만 받아 적는다 — AI 가 날짜를
     * 잘못 뽑아도 조용히 일정이 생기면 안 된다.
     */
    VISIT_FOLLOW_UP
}
