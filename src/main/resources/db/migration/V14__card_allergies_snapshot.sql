-- 알레르기를 카드에 다시 싣는다.
--
-- V11 에서 "프로필에 있는 값이라 카드에 또 두면 두 곳에 남아 어긋난다"는 이유로 뺐다.
-- 그 판단이 틀렸다.
--
-- 카드는 참조가 아니라 스냅샷이다. 이름·나이·성별을 이미 그렇게 박아두고 있고
-- (patient_name · patient_age · patient_sex), 이유도 같다 — 나중에 프로필을 고쳐도
-- 의사가 본 카드는 그대로여야 한다. 알레르기는 그중에서도 바뀌면 안 되는 값이다.
--
-- 화면 근거도 있다. 시안의 카드는 알레르기를 경고 면 맨 위에 올린다
-- ("처방 전에 꼭 확인해 주세요"). 의사에게 보여주는 한 장이 안전 정보를 얻으려고
-- API 를 두 번 부르게 하면 안 된다.
--
-- 복용약은 넣지 않는다. 처방과 직접 부딪히는 값이지만 목록이라 카드 한 장에 자리가
-- 없고, 시안의 카드에도 없다. 필요해지면 그때 같은 방식으로 넣는다.

ALTER TABLE briefing_cards ADD COLUMN allergies_status VARCHAR(16);
ALTER TABLE briefing_cards ADD COLUMN allergies_text VARCHAR(200);
