-- 화면에만 남아 앱을 다시 켜면 사라지던 값 둘에 자리를 준다. 안드로이드 #85.

-- 1. 일정의 진료 전 할 일.
--
-- 1r-4 에서 적고 1r-2 에서 체크한다. 자리가 없어서 앱이 픽스처 세 줄을 보여주고 있었고
-- 체크도 삭제도 화면 안에서만 됐다.
--
-- 일정에 딸린 값이라 별도 테이블을 파지 않는다. 항상 일정과 함께 읽고 쓰고, 줄 하나만
-- 따로 조회할 일이 없다. 앱도 목록째 보내는 쪽을 요청했다.
--
-- [{"text": "달라진 증상 있으면 카드 수정", "done": false}, ...]
ALTER TABLE appointments ADD COLUMN todos JSONB;

-- 2. 진료 하루 전 알림.
--
-- 내 정보(1s-1)의 토글 셋 중 이것만 서버에 둔다. 지금 알림을 예약하는 것은 앱이지만
-- (POST /api/me/devices 참고), 알림을 받을지는 기기 취향이 아니라 그 사람의 선택이다.
-- 기기에만 있으면 기기를 바꾸거나 앱을 다시 깐 뒤 "안 받겠다"고 한 사람에게 알림이
-- 다시 가기 시작한다. 서버 푸시로 옮길 때도 같은 값을 그대로 쓴다.
--
-- 나머지 둘(브리핑 카드 자동 저장 · 진료실 화면 밝기 최대)은 이 기기에서 어떻게 보일지의
-- 문제라 앱의 DataStore 에 둔다. 서버가 읽지도 않는 값을 민감정보 서버에 보관할 이유가 없다.
--
-- 기본값은 켜짐이다. 진료를 놓치지 않게 하는 것이 이 앱의 목적이라, 명시적으로 끄기
-- 전까지는 알린다.
ALTER TABLE users ADD COLUMN visit_reminder_enabled BOOLEAN NOT NULL DEFAULT TRUE;
