-- 카드가 "진료받을 병원"을 기억한다.
--
-- 시안 1m-B 의 버튼이 "브리핑 카드 만들기" 다. 병원을 고른 다음에 카드를 만든다.
-- 그런데 카드 생성에 병원을 받을 자리가 없어서, 앱이 골라도 저장되지 않았다.
--
-- 일정에 두면 안 되는 이유 — 1m-B 에는 날짜 입력이 없어 일정을 만들 수 없다
-- (appointments.scheduled_at 은 NOT NULL). 1r-4-B 에 "병원 미정" 카드가 함께 있는 걸
-- 보면 "병원은 정했는데 일정은 아직 없는" 상태가 정상이다.
--
-- #101 에서 "카드에는 병원이 없다, 일정에서 온다"고 답했던 것을 뒤집는다. 스키마만
-- 보고 시안을 확인하지 않은 판단이었다. 방향이 반대다 — 카드가 병원을 들고,
-- 일정이 그걸 가져간다(1r-4-B 의 "병원 자동").

-- 둘 다 nullable 이다. 1m-B 에 "아직 정하지 않았다면 건너뛰어도 돼요" 가 있어서
-- 병원 없이 만든 카드가 정상이고, 그때 화면은 "병원 미정" 으로 찍는다.
--
-- 이름과 주소를 박아둔다. 요양기호(ykiho)만 저장하고 매번 심평원을 부르는 방법도
-- 있지만 상류 실측이 1.6초이고 일일 할당량이 있다. 무엇보다 카드는 스냅샷이다 —
-- 환자 이름·나이·알레르기·복용약을 전부 만든 시점 값으로 박아두고 있고, 병원 이름이
-- 바뀌거나 폐업해도 "그때 가려던 병원"이 남아야 같은 원칙이다.
--
-- 진료과는 두지 않는다. 심평원 기관명에 이미 들어 있다
-- (The서울아산내과의원 · 배곧서울아산이비인후과의원).
