-- 남아 있는 초안 카드를 전부 확정으로 옮긴다. #181.
--
-- 앱이 "저장하기" 단계를 없앴고, 서버도 카드를 확정된 채로 만든다. 그 전에 저장하지
-- 않고 나간 카드와, 확정한 카드를 고쳐서 생긴 새 버전(편집 뒤에는 앱이 확정을 부르지
-- 않았다)이 DRAFT 로 남아 있다. 앱 목록에는 "진료 전"으로 보이는데 진료 후 기록과
-- 진료실 전달이 막힌다.
--
-- 확정 시각은 카드를 만든 시각으로 둔다. 이 마이그레이션이 돈 시각을 넣으면 실제로 아무
-- 일도 없던 날에 확정된 것처럼 남는다.
--
-- 되돌릴 수 없다. 어느 카드가 초안이었는지가 사라진다. 운영에 내기 전에 pg_dump 를 뜬다.
UPDATE briefing_cards
SET status       = 'CONFIRMED',
    confirmed_at = created_at
WHERE status = 'DRAFT';
