--   · 공유 링크 — IA 의 `1k · 링크로 전달` 이 보류(회색)다. 진료실 전달은
--     `1f · 폰 직접 전달`, 즉 환자가 자기 화면을 보여주는 방식으로 확정됐다.
--   · 되묻기 — `1p · 진료 후 기록` 이 자유 메모를 AI 가 항목으로 나누고
